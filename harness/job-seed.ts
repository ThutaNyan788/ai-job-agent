import type { JobPost, JobSkill } from "@shared/events";

function slug(value: string): string {
  return value.toLowerCase().replace(/[^a-z0-9]+/g, "-").replace(/^-|-$/g, "");
}

function makeJob(
  id: string,
  title: string,
  companyName: string,
  country: string,
  city: string,
  workType: JobPost["location"]["workType"],
  employmentType: JobPost["employmentType"],
  experienceLevel: JobPost["experienceLevel"],
  minYears: number,
  maxYears: number,
  currency: string,
  requiredSkills: JobSkill[],
  niceToHave: string[],
  description: string,
): JobPost {
  return {
    id,
    company: { name: companyName, website: `https://${slug(companyName)}.com` },
    title,
    description,
    location: { country, city, workType },
    employmentType,
    experienceLevel,
    yearsOfExperience: { min: minYears, max: maxYears },
    salary: { min: 4000 + minYears * 500, max: 6500 + maxYears * 500, currency },
    requiredSkills,
    responsibilities: [
      `Build and improve solutions for ${title.toLowerCase()} work`,
      "Collaborate with product and engineering partners",
      "Write clean, maintainable code",
      "Participate in reviews and technical planning",
    ],
    requirements: [`${minYears}+ years of relevant experience`, "Strong communication and problem-solving skills"],
    niceToHave,
    benefits: ["Health insurance", "Learning budget", "Flexible working hours"],
    postedAt: "2026-07-17T10:00:00Z",
    status: "active",
  };
}

